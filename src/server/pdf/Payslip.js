import "server-only";
import { Document, Page, StyleSheet, Text, View, renderToBuffer } from "@react-pdf/renderer";
import { formatMonth } from "@/lib/format";

// Payslip PDF (Spec §4 row 17): company, employee, month, earnings, deductions, tax, net.

const money = (n) => `Rs ${Number(n ?? 0).toLocaleString("en-PK", { minimumFractionDigits: 2, maximumFractionDigits: 2 })}`;

const s = StyleSheet.create({
  page: { padding: 36, fontSize: 10, fontFamily: "Helvetica", color: "#111827" },
  header: { flexDirection: "row", justifyContent: "space-between", borderBottomWidth: 1, borderBottomColor: "#d1d5db", paddingBottom: 10, marginBottom: 14 },
  company: { fontSize: 16, fontFamily: "Helvetica-Bold" },
  muted: { color: "#6b7280" },
  title: { fontSize: 12, fontFamily: "Helvetica-Bold", marginBottom: 6, marginTop: 12 },
  grid: { flexDirection: "row", flexWrap: "wrap" },
  cell: { width: "50%", marginBottom: 4 },
  row: { flexDirection: "row", justifyContent: "space-between", paddingVertical: 4, borderBottomWidth: 0.5, borderBottomColor: "#e5e7eb" },
  bold: { fontFamily: "Helvetica-Bold" },
  net: { flexDirection: "row", justifyContent: "space-between", marginTop: 14, padding: 10, backgroundColor: "#eef2ff", fontSize: 13, fontFamily: "Helvetica-Bold" },
  foot: { position: "absolute", bottom: 30, left: 36, right: 36, color: "#9ca3af", fontSize: 8 },
});

const Line = ({ label, value, bold }) => (
  <View style={s.row}>
    <Text style={bold ? s.bold : undefined}>{label}</Text>
    <Text style={bold ? s.bold : undefined}>{value}</Text>
  </View>
);

function PayslipDocument({ companyName, p }) {
  const deductedDays = p.absentDays + p.unpaidLeaveDays + 0.5 * p.halfDays;
  return (
    <Document title={`Payslip ${p.employeeCode} ${p.month}`}>
      <Page size="A4" style={s.page}>
        <View style={s.header}>
          <View>
            <Text style={s.company}>{companyName}</Text>
            <Text style={s.muted}>Payslip for {formatMonth(p.month)}</Text>
          </View>
          <Text style={s.muted}>{p.runStatus === "finalized" ? "Finalized" : "DRAFT"}</Text>
        </View>

        <View style={s.grid}>
          <Text style={s.cell}>Employee: {p.employeeName}</Text>
          <Text style={s.cell}>Code: {p.employeeCode}</Text>
          <Text style={s.cell}>Department: {p.departmentName ?? "—"}</Text>
          <Text style={s.cell}>Designation: {p.designationTitle ?? "—"}</Text>
          <Text style={s.cell}>Working days: {p.workingDays}</Text>
          <Text style={s.cell}>Days employed: {p.eligibleDays}</Text>
          <Text style={s.cell}>Absent: {p.absentDays} · Unpaid leave: {p.unpaidLeaveDays}</Text>
          <Text style={s.cell}>Half days: {p.halfDays} · Late: {p.lateCount}</Text>
        </View>

        <Text style={s.title}>Earnings</Text>
        <Line label="Basic" value={money(p.basic)} />
        <Line label="House rent allowance (40%)" value={money(p.hra)} />
        <Line label="Medical allowance (10%)" value={money(p.medical)} />
        <Line label="Gross (monthly)" value={money(p.gross)} bold />
        <Line label={`Gross for days employed (${p.eligibleDays}/${p.workingDays})`} value={money(p.proratedGross)} bold />

        <Text style={s.title}>Deductions</Text>
        <Line label={`Absent / unpaid / half days (${deductedDays} days × ${money(p.perDay)})`} value={money(p.deduction)} />
        <Line label="Income tax (monthly)" value={money(p.monthlyTax)} />
        <Line label="Total deductions" value={money(p.deduction + p.monthlyTax)} bold />

        <View style={s.net}>
          <Text>Net pay</Text>
          <Text>{money(p.net)}</Text>
        </View>

        <Text style={s.foot}>Generated by HCM Lite. Tax slabs are illustrative (hackathon brief §3).</Text>
      </Page>
    </Document>
  );
}

export function renderPayslipPdf(companyName, payslip) {
  return renderToBuffer(<PayslipDocument companyName={companyName} p={payslip} />);
}
